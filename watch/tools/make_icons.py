"""Generates Puffble's pixel-art icons (stdlib only, no PIL).

Run from anywhere:  python watch/tools/make_icons.py

Writes:
  watch/resources/images/menu_icon.png                           25x25 watch app-menu icon
  companion/app/src/main/res/drawable/ic_launcher_foreground.xml   Android adaptive icon (vector)
  companion/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml     adaptive icon wrapper
  companion/app/src/main/res/values/ic_launcher_colors.xml         icon background color
"""
import os
import struct
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
WATCH_OUT = os.path.join(ROOT, "watch", "resources", "images")
RES = os.path.join(ROOT, "companion", "app", "src", "main", "res")

# "Puffble": a little flame with a face. O outline, F flame, Y hot core, E eyes and smile.
MASCOT = [
    "......O.....",
    ".....OFO....",
    ".....OFFO...",
    "....OFFFFO.O",
    "...OFFFFFOFO",
    "..OFFFFFFFFO",
    ".OFFYYYYYFFO",
    ".OFYEYYYEYFO",
    ".OFYEYYYEYFO",
    ".OFYYYEYYYFO",
    "..OFYYYYYFO.",
    "...OOOOOOO..",
]
COLORS = {
    "O": (85, 0, 0, 255),       # dark red outline
    "F": (255, 85, 0, 255),     # orange flame
    "Y": (255, 170, 0, 255),    # yellow core
    "E": (0, 0, 0, 255),        # eyes and smile
    ".": (0, 0, 0, 0),
}
ICON_BG = "#1B1B2F"  # Android launcher background behind the mascot


def png(path, width, height, pixels):
    raw = b"".join(b"\x00" + b"".join(bytes(px) for px in row) for row in pixels)

    def chunk(kind, data):
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(raw, 9)))
        f.write(chunk(b"IEND", b""))


def raster(grid, scale, size):
    canvas = [[COLORS["."]] * size for _ in range(size)]
    h, w = len(grid) * scale, len(grid[0]) * scale
    oy, ox = (size - h) // 2, (size - w) // 2
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            for dy in range(scale):
                for dx in range(scale):
                    canvas[oy + y * scale + dy][ox + x * scale + dx] = COLORS[ch]
    return canvas


def vector(grid):
    """Adaptive-icon foreground: 108dp canvas, art inside the 66dp safe zone, 5dp pixels."""
    px = 5
    w, h = len(grid[0]) * px, len(grid) * px
    ox, oy = (108 - w) / 2, (108 - h) / 2
    paths = []
    for ch, rgba in COLORS.items():
        if ch == ".":
            continue
        d = []
        for y, row in enumerate(grid):
            for x, c in enumerate(row):
                if c == ch:
                    x0, y0 = ox + x * px, oy + y * px
                    d.append(f"M{x0:g},{y0:g}h{px}v{px}h-{px}z")
        if d:
            color = "#{:02X}{:02X}{:02X}".format(*rgba[:3])
            paths.append(f'    <path android:fillColor="{color}" android:pathData="{"".join(d)}" />')
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by watch/tools/make_icons.py; edit the grid there, not this file. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp"\n'
        '    android:viewportWidth="108" android:viewportHeight="108">\n'
        + "\n".join(paths)
        + "\n</vector>\n"
    )


# Subset of the watch's 5x7 pixel font (main.c GLYPHS), for store artwork titles.
FONT = {
    "A": (5, [0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11]), "B": (5, [0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E]),
    "C": (5, [0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E]), "E": (5, [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F]),
    "F": (5, [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10]), "I": (3, [0x07, 0x02, 0x02, 0x02, 0x02, 0x02, 0x07]),
    "L": (5, [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F]), "M": (5, [0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11]),
    "N": (5, [0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11]), "O": (5, [0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E]),
    "P": (5, [0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10]), "R": (5, [0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11]),
    "U": (5, [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E]), "X": (5, [0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11]),
    "Y": (5, [0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04]), "W": (5, [0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A]),
    "T": (5, [0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04]), "H": (5, [0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11]),
    " ": (3, [0] * 7),
}


def hex_rgba(h):
    h = h.lstrip("#")
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255)


def stamp_text(canvas, text, x, y, scale, rgba):
    for ch in text:
        w, rows = FONT[ch]
        for r, bits in enumerate(rows):
            for c in range(w):
                if bits & (1 << (w - 1 - c)):
                    for dy in range(scale):
                        for dx in range(scale):
                            canvas[y + r * scale + dy][x + c * scale + dx] = rgba
        x += (w + 1) * scale


def text_width(text, scale):
    return sum((FONT[ch][0] + 1) * scale for ch in text) - scale


def stamp_grid(canvas, grid, x, y, scale):
    for gy, row in enumerate(grid):
        for gx, ch in enumerate(row):
            if ch != ".":
                for dy in range(scale):
                    for dx in range(scale):
                        canvas[y + gy * scale + dy][x + gx * scale + dx] = COLORS[ch]


def store_assets():
    """Pebble app store artwork: large and small icons and a 720x320 banner."""
    out = os.path.join(ROOT, "store")
    os.makedirs(out, exist_ok=True)
    bg = hex_rgba(ICON_BG)
    for size, scale in ((144, 11), (80, 6), (512, 40)):  # store large, small, and a hi-res copy
        canvas = [[bg] * size for _ in range(size)]
        off = (size - 12 * scale) // 2
        stamp_grid(canvas, MASCOT, off, off, scale)
        name = f"icon_{size}.png"
        png(os.path.join(out, name), size, size, canvas)
        print("wrote", os.path.relpath(os.path.join(out, name), ROOT))

    # The store shows the banner as a wide strip that crops away the top and bottom (the
    # dashboard preview keeps roughly the middle 110 px). Everything that matters sits in that
    # middle band, so the banner reads the same cropped or whole.
    w, h = 720, 320
    canvas = [[bg] * w for _ in range(h)]
    white, orange = (255, 255, 255, 255), COLORS["F"]
    title, tagline = "PUFFBLE", "A PEBBLE PUFFCO COMPANION"
    m_scale, t_scale, g_scale = 8, 7, 3
    m_w, m_h = 12 * m_scale, 12 * m_scale
    text_w = max(text_width(title, t_scale), text_width(tagline, g_scale))
    gap = 28
    x0 = (w - (m_w + gap + text_w)) // 2
    mid = h // 2
    stamp_grid(canvas, MASCOT, x0, mid - m_h // 2, m_scale)
    block_h = 7 * t_scale + 12 + 7 * g_scale
    ty = mid - block_h // 2
    tx = x0 + m_w + gap
    stamp_text(canvas, title, tx, ty, t_scale, white)
    stamp_text(canvas, tagline, tx, ty + 7 * t_scale + 12, g_scale, orange)
    png(os.path.join(out, "banner_720x320.png"), w, h, canvas)
    print("wrote", os.path.relpath(os.path.join(out, "banner_720x320.png"), ROOT))


def _vector_xml(width_units, height_units, dp_per_unit, paths):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by watch/tools/make_icons.py; edit it there, not here. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{width_units * dp_per_unit}dp" android:height="{height_units * dp_per_unit}dp"\n'
        f'    android:viewportWidth="{width_units}" android:viewportHeight="{height_units}">\n'
        + "\n".join(paths)
        + "\n</vector>\n"
    )


def tight_vector(grid, colors):
    """The mascot with no padding, for use inside the app (one viewport unit per pixel)."""
    paths = []
    for ch, rgba in colors.items():
        if ch == ".":
            continue
        d = "".join(f"M{x},{y}h1v1h-1z" for y, row in enumerate(grid) for x, c in enumerate(row) if c == ch)
        if d:
            paths.append(f'    <path android:fillColor="#{rgba[0]:02X}{rgba[1]:02X}{rgba[2]:02X}" android:pathData="{d}" />')
    return _vector_xml(len(grid[0]), len(grid), 10, paths)


def text_vector(text, color):
    """[text] in the watch's 5x7 pixel font, as a vector (one viewport unit per font pixel)."""
    d, x = [], 0
    for ch in text:
        w, rows = FONT[ch]
        for r, bits in enumerate(rows):
            for c in range(w):
                if bits & (1 << (w - 1 - c)):
                    d.append(f"M{x + c},{r}h1v1h-1z")
        x += w + 1
    width = x - 1
    return _vector_xml(width, 7, 5, [f'    <path android:fillColor="{color}" android:pathData="{"".join(d)}" />'])


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, ROOT))


